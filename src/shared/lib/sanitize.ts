// ══════════════════════════════════════════════════════════════
//  escapeHtml — تهريب نص قبل إدراجه في HTML (innerHTML / document.write)
//  أي قيمة بيكتبها المستخدم (اسم عميل، ملاحظة، اسم قضية...) ولازم
//  تتعرض جوه HTML خام، لازم تعدي على الدالة دي أولاً — وإلا ممكن
//  حد يحقن <script> أو onerror= وينفّذ كود في متصفح أي مستخدم تاني
//  بيفتح الطباعة (Stored XSS).
// ══════════════════════════════════════════════════════════════
export function escapeHtml(value: unknown): string {
    return String(value ?? '').replace(/[&<>"']/g, (c: string) => ({
        '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
    } as Record<string, string>)[c] as string);
}
// ══════════════════════════════════════════════════════════════
//  normalizeArabicDigits — بيحوّل الأرقام العربية/الفارسية الشرقية
//  (٠١٢٣٤٥٦٧٨٩ / ۰۱۲۳۴۵۶۷۸۹) لأرقام إنجليزية عادية (0-9). القيم
//  المخزّنة في قاعدة البيانات (رقم القضية، الموبايل، الرقم القومي...)
//  دايمًا أرقام إنجليزية عادية، لكن لوحة المفاتيح على موبايل بتبدّل
//  تلقائيًا لأرقام عربية شرقية لو لغة الكيبورد عربي — فالمستخدم بيكتب
//  "٦٣٥٢" في خانة البحث بينما القيمة المخزّنة "6352"، ومطابقة نصية
//  (ilike/includes) عادية مبتلاقيش تطابق خالص لأنهم حروف يونيكود مختلفة
//  تمامًا، مش نفس الرقم بشكل تاني. بنطبّعها هنا قبل أي بحث نصي.
//  باقي الحروف (عربي/إنجليزي) بتفضل زي ما هي بالظبط.
// ══════════════════════════════════════════════════════════════
const ARABIC_INDIC_DIGITS: Record<string, string> = {
    '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
    '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
    '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4',
    '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
};
export function normalizeArabicDigits(value: string): string {
    return value.replace(/[٠-٩۰-۹]/g, (d) => ARABIC_INDIC_DIGITS[d] || d);
}

// ══════════════════════════════════════════════════════════════
//  ilikeOrClause — بناء شرط ilike آمن للاستخدام جوه .or() بتاع PostgREST
//  ⚠️ المشكلة: .or(`col.ilike.%${term}%`) بيكسر لو term فيه فاصلة "," أو
//  قوس "(" أو ")" — PostgREST بيفسّرهم كجزء من صياغة الفلتر نفسها (فاصل
//  بين شروط الـ OR، أو تجميع)، مش كجزء من نص البحث. النتيجة: خطأ في
//  الاستعلام، أو (الأخطر) تفسير جزء من نص المستخدم كشرط فلتر إضافي.
//  الحل الموثّق في PostgREST: أي قيمة فلتر فيها حروف محجوزة (, . : ( ))
//  لازم تتحاط بين علامتي اقتباس مزدوجتين "..."، مع تهريب أي backslash
//  أو علامة اقتباس مزدوجة جوه القيمة نفسها بـ backslash.
//  الاستخدام: q.or([ilikeOrClause('client_name', s), ilikeOrClause('notes', s)].join(','))
//  🔢 FIX (تطبيع الأرقام العربية في البحث — 8 أغسطس 2026): term بيتطبّع
//  بـnormalizeArabicDigits فوق قبل أي حاجة — بيصلّح بحث رقم القضية/
//  الموبايل/الرقم القومي لو المستخدم كتبهم بأرقام عربية شرقية.
// ══════════════════════════════════════════════════════════════
export function ilikeOrClause(column: string, term: string): string {
    const pattern = `%${normalizeArabicDigits(term)}%`;
    const escaped = pattern.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    return `${column}.ilike."${escaped}"`;
}

// ══════════════════════════════════════════════════════════════
//  escapeTelegramHtml — تهريب نص قبل دمجه في رسالة Telegram بصيغة
//  parse_mode: 'HTML'. تيليجرام بيدعم مجموعة محدودة من التاجز
//  (<b>, <i>, <a>...) وبيرفض الرسالة كلها لو فيه < أو > أو & غير
//  متوازن/غير معروف — فلازم نهرّب أي نص حر (عنوان قضية، اسم موكل،
//  ملاحظة) قبل وضعه جوه الرسالة، عشان:
//  ١) ما يكسرش صيغة HTML ويفشل إرسال الإشعار كله.
//  ٢) ما يسمحش لحد يحقن تاجز زي <a href="..."> ويغيّر شكل/سلوك
//     الرسالة (مثلاً يحوّل رابط داخلها لرابط تصيّد).
//  ⚠️ لا تستخدم escapeHtml العادية هنا — هي بتهرّب " و ' كمان وده
//  مش لازم لتيليجرام، والأهم إننا محتاجين الدالة دي منفصلة عشان
//  تفضل تتطبّق على كل نص حر يدخل رسالة تيليجرام مهما كانت الكلاسات
//  اللي حواليها في HTML العادي.
// ══════════════════════════════════════════════════════════════
export function escapeTelegramHtml(value: unknown): string {
    return String(value ?? '').replace(/[&<>]/g, (c: string) => ({
        '&': '&amp;', '<': '&lt;', '>': '&gt;',
    } as Record<string, string>)[c] as string);
}

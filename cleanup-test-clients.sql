-- =========================================================
-- 3) الحذف الفعلي — بيشيل أي موكل رقم تليفونه '01000000000' بالظبط
-- =========================================================
-- client_portal_pins بتتحذف كاسكيد تلقائي (ON DELETE CASCADE)

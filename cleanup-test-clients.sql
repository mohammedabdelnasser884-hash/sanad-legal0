-- تنظيف بيانات موكلين تست قديمة (اتعملت من E2E قبل fix تنظيف الـCI بتاريخ 8 أغسطس)
-- السبب إنها فاضلة: كل تستات E2E اللي بتعمل موكل بتحط نفس رقم التليفون
-- الوهمي بالظبط '01000000000' (utils.ts createClient) — ده أوثق علامة
-- من الاسم، لإن أسماء التستات مش موحّدة (زي اللي شايفها في اسكرين شوت:
